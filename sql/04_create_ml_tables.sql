-- Create views for analytics
CREATE OR REPLACE VIEW CURRENT_HAB_RISKS AS
SELECT 
    p.*,
    h.WATER_TEMP_C,
    h.OXYGEN_MG_L,
    h.PH_LEVEL,
    h.TURBIDITY_NTU
FROM HAB_RISK_PREDICTIONS p
LEFT JOIN HARMONIZED_DATA.HARMONIZED_FARM_DATA h
    ON p.FARM_LOCATION = h.FARM_LOCATION
    AND ABS(DATEDIFF('minute', p.TIMESTAMP, h.TIMESTAMP)) <= 30
WHERE p.CREATED_AT >= DATEADD('hour', -2, CURRENT_TIMESTAMP())
ORDER BY p.RISK_SCORE DESC;

CREATE OR REPLACE VIEW TOP_SALES_OPPORTUNITIES AS
SELECT 
    s.*,
    c.CUSTOMER_NAME,
    c.CUSTOMER_TYPE,
    c.PROFITABILITY_TIER,
    c.RELATIONSHIP_SCORE
FROM SALES_OPPORTUNITY_PREDICTIONS s
JOIN CUSTOMER_PROFILES c ON s.CUSTOMER_ID = c.CUSTOMER_ID
WHERE s.CREATED_AT >= DATEADD('hour', -24, CURRENT_TIMESTAMP())
ORDER BY s.PROBABILITY_SCORE * s.PREDICTED_REVENUE DESC;

-- Create stored procedure for generating sales recommendations
CREATE OR REPLACE PROCEDURE GENERATE_SALES_RECOMMENDATIONS(
    AVAILABLE_VOLUME_KG FLOAT,
    PRODUCT_TYPE VARCHAR
)
RETURNS TABLE (
    CUSTOMER_ID VARCHAR,
    CUSTOMER_NAME VARCHAR,
    RECOMMENDED_VOLUME_KG FLOAT,
    EXPECTED_REVENUE FLOAT,
    PROBABILITY_SCORE FLOAT,
    RECOMMENDATION_RANK INT
)
LANGUAGE SQL
AS
$$
BEGIN
    -- Create temporary table with customer scoring
    CREATE OR REPLACE TEMPORARY TABLE CUSTOMER_SCORES AS
    SELECT 
        c.CUSTOMER_ID,
        c.CUSTOMER_NAME,
        c.AVERAGE_ORDER_SIZE_KG,
        c.AVERAGE_ORDER_VALUE / c.AVERAGE_ORDER_SIZE_KG as PRICE_PER_KG,
        c.PROFITABILITY_TIER,
        c.RELATIONSHIP_SCORE,
        c.RISK_TOLERANCE,
        -- Calculate volume they might want
        LEAST(AVAILABLE_VOLUME_KG * 0.4, c.AVERAGE_ORDER_SIZE_KG * 1.2) as RECOMMENDED_VOLUME,
        -- Calculate probability based on historical patterns and preferences
        CASE 
            WHEN ARRAY_CONTAINS(PRODUCT_TYPE::VARIANT, c.PREFERRED_PRODUCTS) THEN 0.8
            ELSE 0.4
        END * c.RELATIONSHIP_SCORE as BASE_PROBABILITY,
        -- Adjust for recency of last order
        CASE 
            WHEN DATEDIFF('day', c.LAST_ORDER_DATE, CURRENT_DATE()) <= c.PURCHASE_FREQUENCY_DAYS THEN 0.9
            WHEN DATEDIFF('day', c.LAST_ORDER_DATE, CURRENT_DATE()) <= c.PURCHASE_FREQUENCY_DAYS * 1.5 THEN 1.2
            ELSE 0.7
        END as RECENCY_MULTIPLIER
    FROM CUSTOMER_PROFILES c
    WHERE c.CUSTOMER_ID IS NOT NULL;
    
    -- Return ranked recommendations
    LET result_cursor CURSOR FOR
    SELECT 
        CUSTOMER_ID,
        CUSTOMER_NAME,
        RECOMMENDED_VOLUME as RECOMMENDED_VOLUME_KG,
        RECOMMENDED_VOLUME * PRICE_PER_KG as EXPECTED_REVENUE,
        LEAST(BASE_PROBABILITY * RECENCY_MULTIPLIER, 1.0) as PROBABILITY_SCORE,
        ROW_NUMBER() OVER (ORDER BY 
            (BASE_PROBABILITY * RECENCY_MULTIPLIER) * (RECOMMENDED_VOLUME * PRICE_PER_KG) DESC
        ) as RECOMMENDATION_RANK
    FROM CUSTOMER_SCORES
    ORDER BY RECOMMENDATION_RANK
    LIMIT 10;
    
    RETURN TABLE(result_cursor);
END;
$$;
