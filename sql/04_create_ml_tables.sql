-- ML Models and Analytics Tables for FjordSight PoC
-- Tables for storing ML model results and analytics

USE DATABASE FJORDSIGHT_POC;
USE SCHEMA ML_MODELS;

-- HAB risk predictions table
CREATE OR REPLACE TABLE HAB_RISK_PREDICTIONS (
    PREDICTION_ID VARCHAR(100) PRIMARY KEY,
    TIMESTAMP TIMESTAMP_NTZ,
    FARM_LOCATION VARCHAR(100),
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    RISK_SCORE FLOAT,
    RISK_LEVEL VARCHAR(20), -- LOW, MEDIUM, HIGH
    PREDICTION_HORIZON_HOURS INT,
    MODEL_VERSION VARCHAR(50),
    FEATURES VARIANT, -- JSON object with input features
    CONTRIBUTING_FACTORS ARRAY, -- Array of risk factor descriptions
    RECOMMENDATIONS ARRAY, -- Array of recommended actions
    ANOMALY_DETECTED BOOLEAN,
    ANOMALY_SCORE FLOAT,
    MODEL_CONFIDENCE FLOAT,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CLUSTER BY (FARM_LOCATION, DATE_TRUNC('day', TIMESTAMP))
);

-- Sales opportunity predictions (for AI Sales Co-Pilot)
CREATE OR REPLACE TABLE SALES_OPPORTUNITY_PREDICTIONS (
    OPPORTUNITY_ID VARCHAR(100) PRIMARY KEY,
    TIMESTAMP TIMESTAMP_NTZ,
    CUSTOMER_ID VARCHAR(100),
    CUSTOMER_NAME VARCHAR(200),
    PRODUCT_TYPE VARCHAR(100),
    PREDICTED_VOLUME_KG FLOAT,
    PREDICTED_REVENUE FLOAT,
    PROBABILITY_SCORE FLOAT,
    PROFITABILITY_RANK INT,
    HISTORICAL_PREFERENCE_SCORE FLOAT,
    RISK_SCORE FLOAT,
    RECOMMENDATION_REASON VARIANT,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CLUSTER BY (DATE_TRUNC('day', TIMESTAMP), CUSTOMER_ID)
);

-- Model performance metrics
CREATE OR REPLACE TABLE MODEL_PERFORMANCE_METRICS (
    METRIC_ID VARCHAR(100) PRIMARY KEY,
    MODEL_NAME VARCHAR(100),
    MODEL_VERSION VARCHAR(50),
    METRIC_TYPE VARCHAR(50), -- 'accuracy', 'precision', 'recall', 'f1_score', 'mse', 'r2'
    METRIC_VALUE FLOAT,
    EVALUATION_DATE TIMESTAMP_NTZ,
    DATA_PERIOD_START TIMESTAMP_NTZ,
    DATA_PERIOD_END TIMESTAMP_NTZ,
    SAMPLE_SIZE INT,
    NOTES VARCHAR(500),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Customer data for Sales Co-Pilot
CREATE OR REPLACE TABLE CUSTOMER_PROFILES (
    CUSTOMER_ID VARCHAR(100) PRIMARY KEY,
    CUSTOMER_NAME VARCHAR(200),
    CUSTOMER_TYPE VARCHAR(50), -- 'restaurant', 'retailer', 'distributor'
    LOCATION VARCHAR(100),
    PREFERRED_PRODUCTS ARRAY,
    AVERAGE_ORDER_SIZE_KG FLOAT,
    AVERAGE_ORDER_VALUE FLOAT,
    PURCHASE_FREQUENCY_DAYS INT,
    PROFITABILITY_TIER VARCHAR(20), -- 'HIGH', 'MEDIUM', 'LOW'
    RISK_TOLERANCE VARCHAR(20), -- 'HIGH', 'MEDIUM', 'LOW'
    QUALITY_REQUIREMENTS VARCHAR(100),
    PRICE_SENSITIVITY FLOAT, -- 0-1 scale
    LAST_ORDER_DATE TIMESTAMP_NTZ,
    TOTAL_LIFETIME_VALUE FLOAT,
    RELATIONSHIP_SCORE FLOAT, -- 0-1 scale
    NOTES VARIANT,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Historical sales data
CREATE OR REPLACE TABLE SALES_HISTORY (
    SALE_ID VARCHAR(100) PRIMARY KEY,
    CUSTOMER_ID VARCHAR(100),
    FARM_LOCATION VARCHAR(100),
    PRODUCT_TYPE VARCHAR(100),
    VOLUME_KG FLOAT,
    PRICE_PER_KG FLOAT,
    TOTAL_REVENUE FLOAT,
    SALE_DATE TIMESTAMP_NTZ,
    DELIVERY_DATE TIMESTAMP_NTZ,
    QUALITY_GRADE VARCHAR(20),
    CUSTOMER_SATISFACTION_SCORE FLOAT,
    PROFIT_MARGIN FLOAT,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CLUSTER BY (DATE_TRUNC('month', SALE_DATE), CUSTOMER_ID)
);

